import streamlit as st
import pandas as pd, numpy as np, json, joblib
import matplotlib.pyplot as plt
import shap

st.set_page_config(page_title="Exposure-Risk Explorer", layout="wide")

RISK_ORDER = ['Low', 'Moderate', 'High', 'Very High']
RISK_COLORS = {'Low':'#2e7d32','Moderate':'#f9a825','High':'#ef6c00','Very High':'#c62828'}

@st.cache_resource
def load_model():
    return joblib.load('deploy_model.pkl')

@st.cache_data
def load_data():
    X = pd.read_csv('deploy_X.csv')
    meta = pd.read_csv('deploy_meta.csv', parse_dates=['date'])
    with open('feature_cols.json') as f:
        feature_cols = json.load(f)
    return X, meta, feature_cols

@st.cache_resource
def get_explainer(_model):
    return shap.TreeExplainer(_model)

model = load_model()
X, meta, feature_cols = load_data()
explainer = get_explainer(model)

# ---------- conventional AQI (HJ 633-2012 breakpoints) ----------
IAQI = [0,50,100,150,200,300,400,500]
BP = {'PM25':[0,35,75,115,150,250,350,500],'PM10':[0,50,150,250,350,420,500,600],
      'SO2':[0,50,150,475,800,1600,2100,2620],'NO2':[0,80,120,280,565,750,940,1130],
      'CO':[0,2000,4000,14000,24000,36000,48000,60000],'O3':[0,100,160,215,265,800,1000,1200]}
AQI_COL = {'PM25':'PM25','PM10':'PM10','SO2':'SO2','NO2':'NO2','CO':'CO','O3':'O3_8h_max'}

def sub_index(c, bp):
    if pd.isna(c): return np.nan
    for i in range(len(bp)-1):
        if c <= bp[i+1]:
            return IAQI[i] + (IAQI[i+1]-IAQI[i])*(c-bp[i])/(bp[i+1]-bp[i])
    return 500.0

def aqi_for_row(row):
    subs = {p: sub_index(row[AQI_COL[p]], BP[p]) for p in BP}
    valid = {k:v for k,v in subs.items() if not pd.isna(v)}
    val = max(valid.values()); primary = max(valid, key=valid.get)
    cat = ('Excellent' if val<=50 else 'Good' if val<=100 else 'Lightly Polluted'
           if val<=150 else 'Moderately Polluted' if val<=200 else 'Heavily Polluted'
           if val<=300 else 'Severely Polluted')
    return round(val), cat, primary

# ---------- sidebar: choose a real station-day ----------
st.sidebar.header("Select a station-day")
station = st.sidebar.selectbox("Monitoring station", sorted(meta['station_name'].unique()))
sdf = meta[meta['station_name'] == station].sort_values('date')
dates = sdf['date'].dt.date.tolist()
date = st.sidebar.selectbox("Date", dates, index=min(60, len(dates)-1))

idx = meta[(meta['station_name']==station) & (meta['date'].dt.date==date)].index[0]
row = meta.loc[idx]
x = X.loc[[idx]][feature_cols]

# ---------- prediction ----------
pred = int(model.predict(x)[0])
pred_class = RISK_ORDER[pred]
classes = list(model.classes_)
pr = model.predict_proba(x)[0]
proba = [pr[classes.index(i)] for i in range(4)]
true_class = row['risk']

# ---------- header ----------
st.title("Localized Air-Pollution Exposure-Risk Explorer")
st.caption("An explainable machine-learning framework · Beijing Multi-Site data (2013–2017)")

c1, c2, c3 = st.columns([1.1, 1, 1])
with c1:
    st.subheader("Predicted exposure risk")
    st.markdown(f"<h1 style='color:{RISK_COLORS[pred_class]};margin:0'>{pred_class}</h1>",
                unsafe_allow_html=True)
    st.caption(f"{station} · {date} · {row['site_type']} site")
    st.caption(f"Actual class recorded in data: **{true_class}**")
with c2:
    st.subheader("Class probabilities")
    fig, ax = plt.subplots(figsize=(3.4, 2.3))
    ax.barh(RISK_ORDER, proba, color=[RISK_COLORS[c] for c in RISK_ORDER])
    ax.invert_yaxis(); ax.set_xlim(0, 1); ax.set_xticks([])
    for i, p in enumerate(proba): ax.text(p+0.01, i, f"{p:.0%}", va='center', fontsize=8)
    for s in ['top','right','bottom']: ax.spines[s].set_visible(False)
    st.pyplot(fig)
with c3:
    st.subheader("Conventional AQI")
    aqi_val, aqi_cat, primary = aqi_for_row(row)
    st.markdown(f"<h1 style='margin:0'>{aqi_val}</h1>", unsafe_allow_html=True)
    st.caption(f"Category: **{aqi_cat}** · primary pollutant {primary}")
    st.caption("AQI reports only the single worst pollutant.")

st.divider()

# ---------- SHAP explanation ----------
st.subheader(f"Why this prediction?  Factors pushing toward '{pred_class}'")
sv = explainer.shap_values(x)
if isinstance(sv, list):
    svals = np.array(sv[pred])[0]
else:
    arr = np.array(sv)
    svals = arr[0, :, pred] if arr.ndim == 3 else arr[0]
contrib = pd.Series(svals, index=feature_cols).sort_values(key=np.abs, ascending=False).head(12)[::-1]
fig2, ax2 = plt.subplots(figsize=(8, 4.2))
ax2.barh(contrib.index, contrib.values,
         color=['#c62828' if v > 0 else '#2e7d32' for v in contrib.values])
ax2.axvline(0, color='#999', lw=0.8)
ax2.set_xlabel(f"SHAP value   (→ pushes toward {pred_class},  ← pushes away)")
for s in ['top','right']: ax2.spines[s].set_visible(False)
st.pyplot(fig2)
st.caption("Red bars push the prediction toward this risk level; green bars push away. "
           "SHAP shows association with the model's output, not causation.")

st.divider()
st.info("This tool classifies a health-anchored, multi-pollutant **exposure-risk proxy** from "
        "meteorological, temporal and spatial factors only — pollutant concentrations are excluded "
        "by design to keep the prediction non-circular. It is a demonstration prototype, not a "
        "clinical or real-time system.")